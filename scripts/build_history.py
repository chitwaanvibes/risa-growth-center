"""Convert the provided sponsorship workbook into the app's read-only 2025 seed.
Rows are copied unchanged, including the import-retry duplicates the app must remove.
Usage: python3 scripts/build_history.py Sponsor_Dataset.xlsx > public/lib/data/history-source.js"""
import sys, json, datetime as dt, openpyxl
SHEETS = {'Event': 'event', 'Targets': 'targets', 'Brands': 'brands', 'Sponsor contacts': 'contacts',
          'Sponsor campaigns': 'campaigns', 'Sponsor interactions': 'interactions',
          'Brand qualification': 'qualification', 'Partner opportunities': 'opportunities',
          'Opportunity history': 'opp_history', 'Sponsor activations': 'activations'}
def conv(h, v):
    if isinstance(v, dt.datetime):
        v = v + dt.timedelta(microseconds=500000)  # round away float noise
        if h in ('history_start', 'history_end'):
            return v.strftime('%Y-%m-%d')
        return v.strftime('%Y-%m-%dT%H:%M:%S+05:30')
    if isinstance(v, float) and v.is_integer():
        return int(v)
    return v
wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
out = {}
for sheet, key in SHEETS.items():
    rows = [r for r in wb[sheet].iter_rows(values_only=True) if any(v is not None for v in r)]
    head = rows[0]
    out[key] = [{h: conv(h, v) for h, v in zip(head, r) if v is not None} for r in rows[1:]]
out['event'][0]['event_id'] = 'EVENT'
for t in out['targets']:
    t['target_id'] = t['effective_at'][:10]
print('// Generated by scripts/build_history.py from the provided Sponsor_Dataset.xlsx (synthetic). Do not edit.')
print('export default ' + json.dumps(out, ensure_ascii=False) + ';')
